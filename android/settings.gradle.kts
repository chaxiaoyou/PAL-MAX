pluginManagement {
    val flutterSdkPath =
        run {
            val properties = java.util.Properties()
            file("local.properties").inputStream().use { properties.load(it) }
            val flutterSdkPath = properties.getProperty("flutter.sdk")
            require(flutterSdkPath != null) { "flutter.sdk not set in local.properties" }
            flutterSdkPath
        }

    includeBuild("$flutterSdkPath/packages/flutter_tools/gradle")

    repositories {
        // Aliyun mirrors first for faster dependency downloads in China.
        maven { url = uri("https://maven.aliyun.com/repository/google") }
        maven { url = uri("https://maven.aliyun.com/repository/gradle-plugin") }
        maven { url = uri("https://maven.aliyun.com/repository/public") }
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.PREFER_SETTINGS)
    repositories {
        maven { url = uri("https://maven.aliyun.com/repository/google") }
        maven { url = uri("https://maven.aliyun.com/repository/public") }
        // Flutter engine artifacts (io.flutter:...). Honors FLUTTER_STORAGE_BASE_URL
        // so builds in China can use the fast storage.flutter-io.cn mirror.
        val flutterStorageBase = providers
            .environmentVariable("FLUTTER_STORAGE_BASE_URL")
            .orElse("https://storage.googleapis.com")
        maven { url = uri("${flutterStorageBase.get()}/download.flutter.io") }
        google()
        mavenCentral()
    }
}

